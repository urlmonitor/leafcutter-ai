# taken from the working tree at commit 370754072 (316ccfd80 plus merged main).
# A snapshot is needed -- the real tree lost these lists when the consolidation
# landed, and `git show <old commit>` is not available in shallow CI clones.
# Bodies are dropped on purpose.
PRISTINE_TEMPLATES = Path(__file__).resolve().parent / "fixtures_ar_300c" / "templates_pre_migration"


def template_level_ids(fm: dict) -> set[str]:
    """Ids a template's OWN frontmatter ``skills_used`` / ``skills_invoked``
    lists name (third grant source; bare ids or ``{skill_id}`` dicts)."""
    out: set[str] = set()
    for key in TEMPLATE_LEVEL_KEYS:
        for e in fm.get(key) or []:
            out.add(e["skill_id"] if isinstance(e, dict) else e)
    return out


def pristine_template_level() -> dict[str, set[str]]:
    """stem -> template-level ids, from the verbatim pre-migration templates
    that carry a template-level grant list (empty lists give empty sets).
    Derived by parsing, never enumerated by name."""
    out = {}
    for tpl in sorted(PRISTINE_TEMPLATES.glob("*.md")):
        out[tpl.stem] = template_level_ids(template_frontmatter(tpl))
    return out


def strip_frontmatter_keys(text: str, keys: tuple[str, ...]) -> tuple[str, int]:
    """Remove the given top-level keys and their item/continuation lines from
    a template's frontmatter, at TEXT level, changing nothing else. Returns
    (text, lines removed)."""
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        return text, 0
    try:
        end = lines.index("---", 1)
    except ValueError:
        return text, 0
    out, removed, skipping = [lines[0]], 0, False
    for line in lines[1:end]:
        if any(line.startswith(f"{k}:") for k in keys):
            skipping, removed = True, removed + 1
            continue
        if skipping and (line.startswith("- ") or line.startswith(" ") or line.startswith("-\t")):
            removed += 1
            continue
        skipping = False
        out.append(line)
    out.extend(lines[end:])
    return "\n".join(out), removed


def pristine_registry_agents() -> list[dict]:
    """The registry as it was BEFORE consolidation (verbatim git-HEAD bytes
    captured in the fixtures dir): both rival fields, original populations."""
    return json.loads(PRISTINE_REGISTRY.read_text(encoding="utf-8"))["agents"]


def copy_package_slice(dst: Path) -> Path:
    """Copy exactly the inputs the transform hook and the compiler read: the
    real committed templates (declarations included) and the frozen
    pre-consolidation registry with the retired ``skills_used`` field stripped
    (the hook input a stale registry copy looks like). Guard: no template
    declaring ``skills:`` == the real tree gave nothing to regenerate from."""
    (dst / "config").mkdir(parents=True)
    data = json.loads(PRISTINE_REGISTRY.read_text(encoding="utf-8"))
    for agent in data["agents"]:
        agent.pop("skills_used", None)
    (dst / "config" / "agent_registry.json").write_text(json.dumps(data, indent=4) + "\n", encoding="utf-8")
    shutil.copytree(REPO_ROOT / "templates" / "agents", dst / "templates" / "agents")
    shutil.copytree(REPO_ROOT / "templates" / "skills", dst / "templates" / "skills")
    declaring = [t.name for t in (dst / "templates" / "agents").glob("*.md") if GRANT_KEY in template_frontmatter(t)]
    assert declaring, f"guard: 0 templates declare {GRANT_KEY} (empty population)"
    return dst


def run_transform(pkg: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(TRANSFORM_SCRIPT), "--package-root", str(pkg)],
        capture_output=True, text=True, timeout=120, check=False,
    )


def transform_or_fail(pkg: Path) -> None:
    """Run the real transform hook over ``pkg`` (regenerating its registry copy
    from the template declarations); fails when it exits non-zero."""
    proc = run_transform(pkg)
    assert proc.returncode == 0, f"transform hook failed (exit {proc.returncode}): {proc.stderr[-800:]}"


def add_registry_agent(pkg: Path, record: dict) -> None:
    path = pkg / "config" / "agent_registry.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    data["agents"].append(record)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")


def make_skills(root: Path, ids: list[str]) -> Path:
    for sid in ids:
        d = root / sid
        d.mkdir(parents=True, exist_ok=True)
        (d / "SKILL.md").write_text(
            f"---\nname: {sid}\ndescription: fixture skill {sid}\n---\n\nbody\n",
            encoding="utf-8",
        )
    return root


def template_frontmatter(path: Path) -> dict:
    fm, _ = parse_frontmatter(path.read_text(encoding="utf-8"))
    return fm
