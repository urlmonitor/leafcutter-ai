"""Shared helpers for the AR-400 slice-3c tests (hand-off redundancy, proposer retarget, clean build).

TDD red phase. ASSUMED PRODUCTION CONTRACT (the coder implements exactly this; every assertion is
phrased against what the REAL entry points print, return or write, never against a helper name):

  * The registry validator (``python scripts/registry_validator.py``) and the build
    (``scripts/build.py``, validation phase, also ``--validate-only``) report ONE finding line per
    redundant hand-off entry, as an error that fails the run (never a ``[WARNING]``). The line names
    the specialist, the entry, and the covering entry ``__ticket_phase_agents__``, and carries the
    phrase ``redundant hand-off entry`` (matched case-insensitively).
  * A repeat inside ONE declaration is one finding per repeated id carrying the phrase
    ``listed twice`` and naming the specialist and the id (the covering entry listed twice is the
    same kind). Repeats are read from the RAW frontmatter list: the registry copy is regenerated by
    de-duplication, so a check over the registry copy sees nothing.
  * Redundancy is judged against the registry's ``is_ticket_phase`` on every run; the explicit entry
    is never stripped from the declaration or the registry.
  * ``scripts/propose_agent_self_description.py [--agent ID]`` writes
    ``scripts/proposals/agent_self_description_<id>.yaml`` (next to the script, as today). Abilities
    it proposes are listed under ``proposed_frontmatter.skills`` (ids as strings or
    ``{skill_id, mode}`` dicts); no key named ``skills_invoked`` appears anywhere in a proposal; it
    writes nothing under ``config/`` or ``templates/``.

Fixtures: frontmatter bytes come from ``yaml.safe_dump`` (through ``_ar400_3a_fixtures.plant``) and
registry records are deep copies of a real record; slices are REAL copies of ``config/`` +
``templates/agents`` (``make_build_package`` also copies ``scripts/`` and ``docs/`` so a spawned
``build.py`` can never write through into the checked-out tree).
"""

