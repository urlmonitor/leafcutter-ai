REPO_ROOT: Path = F.REPO_ROOT
MACRO = "__ticket_phase_agents__"
SUP = "probe-supervisor"
REDUNDANT = "redundant hand-off entry"
TWICE = "listed twice"
BUILD_TIMEOUT = 900
_ANSI = re.compile(r"\x1b\[[0-9;]*m")


def scratch() -> Path:
    base = Path(tempfile.mkdtemp(prefix="ar400_3c_"))
    atexit.register(shutil.rmtree, str(base), True)
    return base


def new_package() -> Path:
    """A package copy ``<base>/pkg`` (real scripts/docs/templates/config) inside a consumer project ``<base>``."""
    base = scratch()
    root = H.make_build_package(base)
    (base / ".leafcutter" / "skills").mkdir(parents=True)
    return root


# ------------------------------------------------------------------ declarations


def declared_spawn_of(root: Path, name: str) -> list[str]:
    fm, _ = parse_frontmatter((root / F.agent_rel(name)).read_text(encoding="utf-8"))
    return list(fm.get("spawn_allowlist") or [])


def registry_spawn_of(root: Path, name: str) -> list[str]:
    return list(next(a for a in H._registry(root)["agents"] if a["id"] == name).get("spawn_allowlist") or [])


def is_phase(root: Path, agent_id: str) -> bool:
    return bool(next(a for a in H._registry(root)["agents"] if a["id"] == agent_id).get("is_ticket_phase"))


def set_phase(root: Path, agent_id: str, value: bool) -> None:
    """Flip ``is_ticket_phase`` in the registry ONLY (the specialist's definition is untouched)."""
    F.edit_registry(root, agent_id, is_ticket_phase=value)
    assert is_phase(root, agent_id) is value


def set_frontmatter(root: Path, name: str, **keys) -> None:
    """Re-dump one specialist's frontmatter with ``keys`` updated (bytes from yaml.safe_dump)."""
    path = root / F.agent_rel(name)
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---", 3)
    head = yaml.safe_load(text[3:end])
    head.update(keys)
    path.write_text("---\n" + yaml.safe_dump(head, sort_keys=False) + text[end + 1:], encoding="utf-8")


def declare_spawn(root: Path, name: str, raw: list[str]) -> None:
    """Make the specialist's own ``spawn_allowlist`` EXACTLY ``raw`` (repeats kept)."""
    set_frontmatter(root, name, spawn_allowlist=list(raw))
    assert declared_spawn_of(root, name) == list(raw), "the declaration did not round-trip"


def plant_handoff(root: Path, name: str, declared: list[str], *, registry: list[str] | None = None) -> None:
    """Plant a specialist whose frontmatter declares ``declared`` verbatim. The derived registry copy
    is ``registry`` (default: the declaration de-duplicated, which is what the commit-time transform
    writes); its children's ``spawned_by`` are kept symmetric."""
    derived = tuple(dict.fromkeys(declared if registry is None else registry))
    F.plant(root, name, [H.FILLER], spawn=derived, described=True)
    declare_spawn(root, name, declared)
    assert registry_spawn_of(root, name) == list(derived)


# ------------------------------------------------------------------ doors


def run_build(root: Path, target: Path, *extra: str) -> tuple[int, str]:
    """A real ``build.py --target-dir <target>`` run from ``root`` -> (exit, stdout+stderr, ANSI stripped)."""
    cp = subprocess.run([sys.executable, str(root / "scripts" / "build.py"), "--target-dir", str(target), *extra],
                        capture_output=True, text=True, timeout=BUILD_TIMEOUT, check=False)
    return cp.returncode, _ANSI.sub("", cp.stdout + "\n" + cp.stderr)


def two_doors(root: Path) -> dict[str, tuple[int, str]]:
    """The validator CLI and the build's validation phase (``--validate-only``: no deploy) over ``root``."""
    return {"validator": H.cli(root), "build": run_build(root, root.parent, "--validate-only")}


def hand_off_hits(out: str, *phrases: str) -> list[str]:
    """Distinct finding lines (door prefix stripped, print order) carrying one of ``phrases``."""
    wanted = phrases or (REDUNDANT, TWICE)
    return list(dict.fromkeys(F.normalise(ln) for ln in out.splitlines()
                              if any(p in ln.lower() for p in wanted)))


def redundancy_warnings(out: str) -> list[str]:
    """``[WARNING]`` lines that talk about redundancy (the pre-3c wording is '...is redundantly listed...')."""
    return [ln.strip() for ln in out.splitlines() if "[WARNING]" in ln and "redundant" in ln.lower()]


def names_all(line: str, *tokens: str) -> bool:
    return all(F.names(line, t) for t in tokens)


def compiled_prompts(project: Path, agent: str) -> dict[str, str]:
    """``{platform root: compiled prompt}`` for ``agent`` in every root the build wrote."""
    texts = {str(r): (r / f"{agent}.md").read_text(encoding="utf-8")
             for r in compiled_agent_roots(project) if (r / f"{agent}.md").is_file()}
    assert texts, f"build wrote no compiled prompt for {agent} under {project / '.leafcutter'}"
    return texts


def hand_off_ids(text: str, agent: str) -> list[str]:
    """The ids of the ONE sub-agent account in a compiled prompt (asserts there is exactly one)."""
    accounts = spawn_accounts(text, real_known_ids() | {agent})
    assert len(accounts) == 1, f"{len(accounts)} hand-off accounts"
    return accounts[0]["ids"]


# ------------------------------------------------------------------ the f-1 scenario (shared)


def plant_redundant(root: Path) -> None:
    """probe-supervisor declares [macro, brainstorm-lead, llm-expert]; llm-expert is a ticket-phase agent,
    brainstorm-lead is not. The derived registry copy omits llm-expert, so a check that reads the registry
    copy instead of the declaration finds nothing."""
    assert is_phase(root, "llm-expert") and not is_phase(root, "brainstorm-lead")
    plant_handoff(root, SUP, [MACRO, "brainstorm-lead", "llm-expert"], registry=[MACRO, "brainstorm-lead"])


@functools.lru_cache(maxsize=1)
def redundant_run() -> dict:
    """The f-1 fixture run through both real doors once per process (full build: refuses before deploy)."""
    root = new_package()
    plant_redundant(root)
    return {"root": root, "validator": H.cli(root), "build": run_build(root, root.parent)}


# ------------------------------------------------------------------ proposer (AR-400e-3)


def proposer_package() -> Path:
    """A slice with a REAL copy of ``scripts/`` (minus the shipped proposals) so the proposer runs from it."""
    root = H.make_slice(scratch())
    shutil.copytree(REPO_ROOT / "scripts", root / "scripts", ignore=shutil.ignore_patterns("__pycache__", "proposals"))
    return root


def run_proposer(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(root / "scripts" / "propose_agent_self_description.py"), *args],
                          capture_output=True, text=True, timeout=600, cwd=str(root), check=False)


def proposals(root: Path, agent: str | None = None) -> list[dict]:
    folder = root / "scripts" / "proposals"
    docs = [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(folder.glob("*.yaml"))] if folder.is_dir() else []
    return [d for d in docs if isinstance(d, dict) and (agent is None or d.get("agent_id") == agent)]


def _skill_id(entry) -> str:
    return entry if isinstance(entry, str) else str(entry.get("skill_id"))


def proposed_frontmatter_ids(doc: dict) -> set[str]:
    """Ability ids the proposal puts into the specialist's own ``skills:`` declaration."""
    return {_skill_id(e) for e in ((doc.get("proposed_frontmatter") or {}).get("skills") or [])}


def _walk(node):
    if isinstance(node, dict):
        for key, value in node.items():
            yield key, value
            yield from _walk(value)
    elif isinstance(node, list):
        for value in node:
            yield from _walk(value)


def ability_ids_anywhere(doc: dict) -> set[str]:
    """Every ability id listed under a ``skills`` / ``skills_invoked`` key anywhere in the proposal."""
    return {_skill_id(e) for key, value in _walk(doc) if key in ("skills", "skills_invoked")
            and isinstance(value, list) for e in value}


def has_key(doc: dict, wanted: str) -> bool:
    return any(key == wanted for key, _ in _walk(doc))


def digest(root: Path, *relative: str) -> dict[str, str]:
    """sha256 of every file under the given repo-relative paths (a directory is walked)."""
    out: dict[str, str] = {}
    for rel in relative:
        base = root / rel
        for path in ([base] if base.is_file() else sorted(p for p in base.rglob("*") if p.is_file())):
            out[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return out


def plant_probe(root: Path, name: str, body: list[str], *, signoff: bool = False) -> None:
    """A specialist whose ``skills:`` declaration grants nothing; ``signoff: true`` when asked."""
    F.plant(root, name, body, grants=())
    if signoff:
        set_frontmatter(root, name, signoff=True)
    fm, _ = parse_frontmatter((root / F.agent_rel(name)).read_text(encoding="utf-8"))
    assert not fm.get("skills"), "the fixture must grant nothing"


def declared_pairs(root: Path, name: str) -> list[tuple[str, str]]:
    return [(e["skill_id"], e["mode"]) for e in E.declared(root)[name]]


def registry_pairs(root: Path, name: str) -> list[tuple[str, str]]:
    rec = next(a for a in E.registry(root)["agents"] if a["id"] == name)
    return [(e["skill_id"], e.get("mode") or "always") for e in rec.get("skills_invoked") or []
            if not e.get("descriptive_only")]


# ------------------------------------------------------------------ AR-400c-4


def ticket_supervisor_with_llm_expert(root: Path) -> None:
    """Restore the 2026-10-12 leftover: ticket-supervisor lists llm-expert beside the macro (declaration
    AND derived copy, so the redundancy is the ONLY inconsistency in the copy)."""
    F.swap(root / F.agent_rel("ticket-supervisor"), "- brainstorm-lead\n- test-breaker\n",
           "- brainstorm-lead\n- llm-expert\n- test-breaker\n")
    derived = registry_spawn_of(root, "ticket-supervisor")
    derived.insert(derived.index("brainstorm-lead") + 1, "llm-expert")
    F.edit_registry(root, "ticket-supervisor", spawn_allowlist=derived)
    assert declared_spawn_of(root, "ticket-supervisor") == derived


@functools.lru_cache(maxsize=1)
def restored_copy() -> Path:
    root = new_package()
    ticket_supervisor_with_llm_expert(root)
    return root


@functools.lru_cache(maxsize=1)
def real_validate_only() -> tuple[int, str]:
    """``build.py --validate-only`` over the checked-out package: the validation phase of a real build
    (registry validator + ability gate), without the ~60 s deploy. Writes nothing."""
    with tempfile.TemporaryDirectory() as tmp:
        return run_build(REPO_ROOT, Path(tmp), "--validate-only")


def definitions_in_tree(root: Path) -> int:
    """Specialist definitions: registry agents whose template is a file under ``templates/agents/``."""
    agents = json.loads((root / "config" / "agent_registry.json").read_text(encoding="utf-8"))["agents"]
    return sum(1 for a in agents if a.get("template_path") and (root / a["template_path"]).is_file()
               and (root / a["template_path"]).parent == root / "templates" / "agents")
