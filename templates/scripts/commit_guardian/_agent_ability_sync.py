"""
MODULE: _agent_ability_sync
GOAL: Shared, pure helpers that turn an agent template's frontmatter ``skills``
    declaration into the ability fields of that agent's registry record.
BUSINESS CONTEXT: AR-300c made each template's frontmatter ``skills:`` list the
    source of truth for an agent's abilities; the registry's ``skills_invoked``
    field is a DERIVED copy (the older ``skills_used`` list is retired, AR-400e).
    The pre-commit transform hook (``transform_agent_registry.py``) writes that
    copy, so the regeneration rule lives here once.
ARCHITECTURE: Pure functions, no git and no network. ``declared_entries``
    parses a template's frontmatter into ``{skill_id, mode[, condition]
    [, provided_by]}`` entries; ``regenerate_record`` rewrites ONE registry
    record's ``skills_invoked`` in place (exactly the declared grants, then the
    ``descriptive_only`` entries, which describe behaviour and are not grants)
    and drops ``skills_used`` from the record; ``declared_spawn`` and
    ``regenerate_spawn`` do the same for the sub-agent permission (AR-300c-5-ii:
    the registry's ``spawn_allowlist`` is the derived copy of the template's
    ``spawn_allowlist`` declaration, macro kept as written, absent -> ``[]``);
    ``dump_registry`` serialises the
    registry the one way both tools write it. The commit_guardian directory is
    copied wholesale by the build, so this sibling module reaches the deployed
    hook with no deploy-manifest entry. The migration imports it by path.

DECISION HISTORY
- 2026-10-09 [python-coder/AR-300c-3]: Created. The regeneration rule moved
  here from ``migrate_agent_abilities.py`` so the transform hook (user
  decision, BrainCandy 2026-10-09: the registry copy is regenerated by a
  pre-commit transform, never by the build) shares it byte for byte.
  (#AR-300c-3)
- 2026-10-09 [python-coder/AR-300c-2]: ``regenerate_record`` now puts a
  declaration into ``skills_invoked`` when the record held neither field, so a
  newly granted agent is never silently left out of the derived copy.
  (#AR-300c-2)
- 2026-10-09 [python-coder/AR-300c-5]: Added ``declared_spawn`` and
  ``regenerate_spawn`` so the transform hook regenerates the registry's
  sub-agent lists from the declarations too. (#AR-300c-5-ii)
- 2026-10-12 [python-coder/AR-400e-2]: ``regenerate_record`` now writes ONLY
  ``skills_invoked`` (declared grants incl. ``provided_by``, then preserved
  descriptive_only entries) and drops ``skills_used``; the per-field
  population rule is gone and the one-shot migration helper is retired.
  (#AR-400e-2)
"""

from __future__ import annotations

import json
from typing import Any

DEFAULT_MODE = "always"
INVOKED_FIELD = "skills_invoked"
RETIRED_FIELD = "skills_used"  # retired (AR-400e): never written, dropped from records that carry it
_ABILITY_FIELDS = (RETIRED_FIELD, INVOKED_FIELD)
_OPTIONAL_KEYS = ("condition", "provided_by")
SPAWN_FIELD = "spawn_allowlist"


def entry_id(item: Any) -> str | None:
    """Return the skill id of a registry ability item (string or dict)."""
    sid = item.get("skill_id") if isinstance(item, dict) else item
    return sid if isinstance(sid, str) else None


def field_ids(agent: dict[str, Any], field: str) -> list[str]:
    """Return every skill id recorded in ``field`` (descriptive entries included)."""
    return [sid for sid in map(entry_id, agent.get(field) or []) if sid]


def descriptive_entries(agent: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    """Return ``(field, entry)`` for every descriptive_only entry on the record."""
    return [
        (field, item)
        for field in _ABILITY_FIELDS
        for item in agent.get(field) or []
        if isinstance(item, dict) and item.get("descriptive_only")
    ]


class MalformedDeclarationError(ValueError):
    """A ``skills`` / ``spawn_allowlist`` value is malformed (the message names the offending value).

    The build gate (``scripts/agent_declaration_shape``) applies the same rules;
    this hook is deployed on its own, so it carries its own copy of them.
    """

    def __init__(self, problems: list[str]) -> None:
        """Join ``problems`` (one message per offending value) into the exception message."""
        super().__init__("; ".join(problems))


def _skill_problem(item: Any) -> str | None:
    """Return what is wrong with one ``skills`` entry, or None when it is well-formed."""
    if isinstance(item, str):
        return None
    if not isinstance(item, dict) or not isinstance(item.get("skill_id"), str):
        return f"entry {item!r} is not a skill id string or a mapping with a string 'skill_id'"
    mode = item.get("mode")
    if mode is not None and mode not in ("always", "conditional"):
        return f"entry {item!r} has mode {mode!r} (expected always or conditional)"
    return None


def _skills_problems(raw: Any) -> list[str]:
    """Return one message per defect in a non-empty ``skills`` value."""
    if not isinstance(raw, list):
        return [f"skills must be a list, got {type(raw).__name__} {raw!r}"]
    return [p for p in map(_skill_problem, raw) if p]


def _spawn_problems(raw: Any) -> list[str]:
    """Return one message per defect in a non-empty ``spawn_allowlist`` value."""
    if not isinstance(raw, list):
        return [f"{SPAWN_FIELD} must be a list, got {type(raw).__name__} {raw!r}"]
    return [f"{SPAWN_FIELD} entry {item!r} is not an agent id string" for item in raw if not isinstance(item, str)]


def normalize_declared(raw: Any) -> list[dict[str, str]]:
    """Normalise a frontmatter ``skills`` value to ``{skill_id, mode[, condition]}`` dicts.

    A bare string is an ``always`` grant of that id.

    Raises:
        MalformedDeclarationError: When ``raw`` is not a list or an entry is malformed.
    """
    out: list[dict[str, str]] = []
    if not raw:
        return out
    problems = _skills_problems(raw)
    if problems:
        raise MalformedDeclarationError(problems)
    for item in raw:
        entry = {"skill_id": item} if isinstance(item, str) else item
        norm = {"skill_id": entry["skill_id"], "mode": entry.get("mode") or DEFAULT_MODE}
        for key in _OPTIONAL_KEYS:
            if entry.get(key):
                norm[key] = str(entry[key])
        out.append(norm)
    return out


def frontmatter_of(text: str) -> dict[str, Any] | None:
    """Parse a template's leading ``---`` frontmatter block.

    Returns:
        The mapping, ``{}`` for an empty block, or None when ``text`` has no
        frontmatter block. Raises ``yaml.YAMLError`` on malformed YAML so the
        caller (the I/O boundary) decides how to report it.
    """
    lines = text.splitlines()
    if not lines or lines[0].rstrip() != "---":
        return None
    close = next((i for i in range(1, len(lines)) if lines[i].rstrip() == "---"), None)
    if close is None:
        return None
    import yaml  # noqa: PLC0415 - lazy: a missing PyYAML must reach the caller's fail-open path

    loaded = yaml.safe_load("\n".join(lines[1:close]))
    return loaded if isinstance(loaded, dict) else {}


def declared_entries(text: str) -> list[dict[str, str]] | None:
    """Return a template's declared grants, or None when it has no frontmatter."""
    fm = frontmatter_of(text)
    return None if fm is None else normalize_declared(fm.get("skills"))


def declared_spawn(fm: dict[str, Any] | None) -> list[str]:
    """Return the ids in a template's ``spawn_allowlist`` declaration, each once, in order.

    The ticket-phase macro is an ordinary entry and is kept as written. An absent
    key, an empty list or no frontmatter all yield ``[]`` (no permission).

    Raises:
        MalformedDeclarationError: When the value is not a list or an entry is not a string.
    """
    raw = (fm or {}).get(SPAWN_FIELD)
    if not raw:
        return []
    problems = _spawn_problems(raw)
    if problems:
        raise MalformedDeclarationError(problems)
    return list(dict.fromkeys(raw))


def regenerate_spawn(agent: dict[str, Any], declared: list[str]) -> None:
    """Rewrite the record's derived ``spawn_allowlist`` from the declaration, in place.

    Touches no other field -- ``spawned_by`` and ``is_ticket_phase`` are authored
    in the registry, not derived.
    """
    agent[SPAWN_FIELD] = list(declared)


def regenerate_record(agent: dict[str, Any], entries: list[dict[str, str]]) -> None:
    """Rewrite the record's one ability field, ``skills_invoked``, from ``entries`` in place.

    ``skills_invoked`` becomes exactly the declared grants (mode, condition and
    ``provided_by`` as declared) followed by the record's preserved
    descriptive_only entries. The retired ``skills_used`` field is never
    written and is dropped from a record that still carries it.

    Args:
        agent: The registry agent record to update.
        entries: The agent's declaration entries.
    """
    descriptive = [item for _f, item in descriptive_entries(agent)]
    agent[INVOKED_FIELD] = [dict(e) for e in entries] + descriptive
    agent.pop(RETIRED_FIELD, None)


def dump_registry(data: dict[str, Any]) -> str:
    """Serialise the registry exactly as both writers do (4-space indent, UTF-8, final newline)."""
    return json.dumps(data, indent=4, ensure_ascii=False) + "\n"
