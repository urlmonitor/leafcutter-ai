"""
MODULE: migrate_agent_spawn_allowlist
GOAL: One-shot migration that moves each agent's permitted sub-agents from every
    place they were recorded into the agent's own template frontmatter
    ``spawn_allowlist`` key, and reports where each permission came from.
BUSINESS CONTEXT: AR-300c-5-i made the template frontmatter the single source of
    truth for which sub-agents an agent may dispatch. Permissions were recorded
    in THREE places that disagree: the registry's ``spawn_allowlist``, a
    ``spawn_allowlist`` key some templates already carried, and hand-written
    ``## Your Available Sub-Agents`` tables in five template bodies. The declared
    list is the UNION of all three -- dropping any would silently revoke a
    permission (python-coder's table named ``test-runner`` that the registry
    omitted; the registry gave architect-review a permission its table never
    listed). The ticket-phase macro ``__ticket_phase_agents__`` is
    carried as ONE entry, never expanded into the agents it stands for today.
ARCHITECTURE: ``python scripts/migrate_agent_spawn_allowlist.py --package-root
    DIR [--report PATH]`` reads ``DIR/config/agent_registry.json`` and
    ``DIR/templates/agents/*.md`` (files starting ``_`` are partials). Per
    template it unions the three sources (existing declaration first, then the
    registry list, then the body table) and writes ONLY the ``spawn_allowlist``
    key, beside ``tools:`` (text level, so every other frontmatter line and the
    body stay byte-identical). An agent permitted nothing by any source gains no
    key, and an existing declaration already equal to the union is left alone
    (so an explicit empty list is never touched and a re-run is byte-stable). It
    never writes the registry: the derived copy is regenerated by the
    ``transform-agent-registry`` hook. The report lists, per permitted agent,
    each sub-agent with the sources that named it (``registry`` /
    ``frontmatter`` / ``body_table``), the agents whose non-empty sources
    disagree, and how many agents each source held. Hand tables are not deleted
    here -- that is an authoring step done after the declaration exists. Not
    wired into the build. Build-engine script under ``scripts/``; no
    deploy-manifest entry needed.

DECISION HISTORY
- 2026-10-09 [python-coder/AR-300c-5-i]: Created, modelled on
  ``migrate_agent_abilities``. A registry record with permissions but no
  template file cannot receive a declaration and is listed under ``review``
  instead of being dropped silently. (#AR-300c-5-i)
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "templates" / "scripts" / "commit_guardian"))

from _agent_ability_sync import declared_spawn, frontmatter_of  # noqa: E402

_log = logging.getLogger(__name__)

KEY = "spawn_allowlist"
SOURCES = ("registry", "frontmatter", "body_table")
_TABLE_HEADING = "## Your Available Sub-Agents"
_ROW_RE = re.compile(r"^\|\s*([a-z][a-z0-9-]*)\s*\|")
_FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")


def body_table_ids(text: str) -> list[str]:
    """Return the agent ids in the hand-written sub-agent table of ``text``, in row order, each once.

    The table is the run of ``|`` rows under the exact heading
    ``## Your Available Sub-Agents`` (to the next ``## `` heading), outside code
    fences; the column header row is not an agent.
    """
    ids: list[str] = []
    inside, fenced = False, False
    for line in text.splitlines():
        if _FENCE_RE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        if line.strip() == _TABLE_HEADING:
            inside = True
            continue
        if inside and line.startswith("## "):
            break
        row = _ROW_RE.match(line) if inside else None
        if row and row.group(1) != "agent" and row.group(1) not in ids:
            ids.append(row.group(1))
    return ids


def union_ids(frontmatter: list[str], registry: list[str], table: list[str]) -> list[str]:
    """Return the union of the three sources: declaration first, then registry, then table; each id once."""
    return list(dict.fromkeys([*frontmatter, *registry, *table]))


def _key_span(lines: list[str], start: int, stop: int, key: str) -> tuple[int, int] | None:
    """Return the ``[first, end)`` line span of top-level ``key`` in ``lines[start:stop]``."""
    for i in range(start, stop):
        if lines[i].startswith(f"{key}:"):
            end = i + 1
            while end < stop and lines[end][:1] in (" ", "-", "\t"):
                end += 1
            return i, end
    return None


def rewrite_frontmatter(text: str, ids: list[str]) -> str | None:
    """Return ``text`` with the ``spawn_allowlist`` key set to ``ids``; every other byte is unchanged.

    The key is inserted after ``tools:`` (or before the closing ``---`` when
    there is no ``tools:``) and an existing block is replaced in place.

    Returns:
        The new text, or None when ``text`` has no frontmatter block.
    """
    eol = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip() != "---":
        return None
    close = next((i for i in range(1, len(lines)) if lines[i].rstrip() == "---"), None)
    if close is None:
        return None
    dumped = yaml.safe_dump({KEY: ids}, sort_keys=False, default_flow_style=False, allow_unicode=True, width=10**6)
    block = [line + eol for line in dumped.splitlines()]
    existing = _key_span(lines, 1, close, KEY)
    if existing:
        lines[existing[0]:existing[1]] = block
    else:
        tools = _key_span(lines, 1, close, "tools")
        at = tools[1] if tools else close
        lines[at:at] = block
    return "".join(lines)


def _read_text(path: Path) -> str:
    """Read a UTF-8 file, logging and re-raising on failure."""
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        _log.warning("cannot read %s: %s", path, exc)
        raise


def _write_if_changed(path: Path, new_text: str, old_text: str) -> None:
    """Write ``new_text`` (bytes, no newline translation) only when it differs."""
    if new_text == old_text:
        return
    try:
        path.write_bytes(new_text.encode("utf-8"))
    except OSError as exc:
        _log.warning("cannot write %s: %s", path, exc)
        raise


def _frontmatter_or_none(path: Path, text: str) -> dict[str, Any] | None:
    """Return the template's frontmatter mapping, or None (after a WARNING) when unparsable."""
    try:
        return frontmatter_of(text)
    except yaml.YAMLError as exc:
        _log.warning("cannot parse frontmatter of %s: %s", path, exc)
        return None


def _agent_entry(agent_id: str, sources: dict[str, list[str]], union: list[str]) -> dict[str, Any]:
    """Return the report row of one permitted agent: each sub-agent with the sources that named it."""
    return {"agent": agent_id,
            "sub_agents": [{"id": sid, "sources": [name for name in SOURCES if sid in sources[name]]}
                           for sid in union]}


def _declare(path: Path, agent_id: str, registry_ids: list[str], report: dict[str, Any]) -> None:
    """Union one template's sources, write its declaration when it changes, and add its report rows."""
    old = _read_text(path)
    fm = _frontmatter_or_none(path, old)
    sources = {"registry": registry_ids, "frontmatter": declared_spawn(fm), "body_table": body_table_ids(old)}
    union = union_ids(sources["frontmatter"], sources["registry"], sources["body_table"])
    if fm is None:
        if union:
            report["review"].append({"agent": agent_id, "note": "template has no parsable frontmatter block; "
                                                               "sub-agents not declared"})
        return
    if not union:
        return
    if union != sources["frontmatter"]:
        new = rewrite_frontmatter(old, union)
        if new is not None:
            _write_if_changed(path, new, old)
    report["agents"].append(_agent_entry(agent_id, sources, union))
    held = [set(ids) for ids in sources.values() if ids]
    if any(group != held[0] for group in held):
        report["disagreeing_agents"].append(agent_id)
    for name in SOURCES:
        report["source_holder_counts"][name] += 1 if sources[name] else 0


def migrate(package_root: Path) -> dict[str, Any]:
    """Run the migration over ``package_root`` and return the report dict.

    Args:
        package_root: Directory holding ``config/agent_registry.json`` and
            ``templates/agents/``.

    Returns:
        The report: ``agents``, ``disagreeing_agents``, ``source_holder_counts``
        and ``review`` (permissions that could not be declared).
    """
    data = json.loads(_read_text(package_root / "config" / "agent_registry.json"))
    report: dict[str, Any] = {"agents": [], "disagreeing_agents": [],
                              "source_holder_counts": dict.fromkeys(SOURCES, 0), "review": []}
    claimed: set[Path] = set()
    for agent in data["agents"]:
        template_path = agent.get("template_path")
        path = package_root / template_path if template_path else None
        if path is not None and path.is_file():
            claimed.add(path.resolve())
            _declare(path, agent["id"], list(agent.get("spawn_allowlist") or []), report)
        elif agent.get("spawn_allowlist"):
            report["review"].append({"agent": agent["id"], "note": "no template file; permissions not declared"})
    agents_dir = package_root / "templates" / "agents"
    for path in sorted(agents_dir.glob("*.md")) if agents_dir.is_dir() else []:
        if not path.name.startswith("_") and path.resolve() not in claimed:
            _declare(path, path.stem, [], report)
    return report


def main(argv: list[str] | None = None) -> int:
    """CLI entry point; returns the process exit code (0 on success)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else None)
    parser.add_argument("--package-root", required=True, type=Path)
    parser.add_argument("--report", type=Path, default=None)
    args = parser.parse_args(argv)
    report = migrate(args.package_root.resolve())
    if args.report:
        try:
            args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        except OSError as exc:
            _log.warning("cannot write report %s: %s", args.report, exc)
            raise
    print(f"permitted agents: {len(report['agents'])}; disagreeing: {len(report['disagreeing_agents'])}; "
          f"holders by source: {report['source_holder_counts']}; review: {len(report['review'])}")
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.WARNING, stream=sys.stderr)
    sys.exit(main())
