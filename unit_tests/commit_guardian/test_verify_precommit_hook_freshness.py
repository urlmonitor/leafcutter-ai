"""
MODULE: test_verify_precommit_hook_freshness
GOAL: Tests for check_hook_freshness in scripts/commit_guardian/verify_precommit_active.py.
BUSINESS CONTEXT: The pre-commit probe reports "hook_freshness" in failing_checks
    when the installed pre-commit hook is stale, and the commit step then refuses
    to commit (fail-closed). Freshness must mean "the installed hook would behave
    like a freshly installed one", judged by the hook's content, never by its age:
    linked git worktrees share one hook in the common git dir while each checks out
    a newer config, so an age rule flags every new worktree although the hook is
    byte-identical to what `pre-commit install` would write.
ARCHITECTURE: Each test builds a temp layout with the hook in a shared hooks dir
    (``<tmp>/common-git/hooks/pre-commit``) and the config in the worktree
    (``<tmp>/worktree/.pre-commit-config.yaml``), writes a hook shaped exactly like
    pre-commit's templated shim, and calls check_hook_freshness directly.

====================================================================
DECISION HISTORY
====================================================================
- 2026-11-25 [BO-1700h-4]: Created. Moved TestCheckHookFreshness out of
  test_verify_precommit_active.py (over its size limit) and rewrote it for the
  content-based freshness rule. The mtime tests (newer/same/older than config,
  all with a "#!/bin/sh" stub hook) encoded the false positive -- a correct shim
  older than the config failed -- so they were replaced by real pre-commit-shaped
  shims: an older/newer correct shim passes, a .leafcutter/ config resolves
  against the project root, and non-shim / other hook type / missing config /
  missing interpreter / missing hook all fail.
====================================================================
"""

from __future__ import annotations

import os
import sys
import tempfile
import unittest
from pathlib import Path

import scripts.commit_guardian.verify_precommit_active as _vpa  # type: ignore[import]


def _write_precommit_shim(
    hook_path: Path,
    install_python: str,
    config_arg: str = ".pre-commit-config.yaml",
    hook_type: str = "pre-commit",
) -> None:
    """Write a hook file shaped exactly like the shim ``pre-commit install`` writes.

    Mirrors pre-commit's ``resources/hook-tmpl`` after templating (the header
    marker, the ``INSTALL_PYTHON=`` line and the ``ARGS=(hook-impl ...)`` line),
    so the freshness check is exercised against the real installed shape.
    """
    hook_path.parent.mkdir(parents=True, exist_ok=True)
    hook_path.write_text(
        "#!/usr/bin/env bash\n"
        "# File generated by pre-commit: https://pre-commit.com\n"
        "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
        "\n"
        "# start templated\n"
        f"INSTALL_PYTHON={install_python}\n"
        f"ARGS=(hook-impl --config={config_arg} --hook-type={hook_type})\n"
        "# end templated\n"
        "\n"
        'HERE="$(cd "$(dirname "$0")" && pwd)"\n'
        'ARGS+=(--hook-dir "$HERE" -- "$@")\n'
        "\n"
        'if [ -x "$INSTALL_PYTHON" ]; then\n'
        '    exec "$INSTALL_PYTHON" -mpre_commit "${ARGS[@]}"\n'
        "elif command -v pre-commit > /dev/null; then\n"
        '    exec pre-commit "${ARGS[@]}"\n'
        "else\n"
        "    echo '`pre-commit` not found.  Did you forget to activate your virtualenv?' 1>&2\n"
        "    exit 1\n"
        "fi\n",
        encoding="utf-8",
    )


def _age_hook_behind_config(hook_path: Path, config_path: Path) -> None:
    """Make the hook 100 seconds older than the config (the linked-worktree shape)."""
    config_stat = config_path.stat()
    os.utime(hook_path, (config_stat.st_atime - 100, config_stat.st_mtime - 100))


class TestCheckHookFreshness(unittest.TestCase):
    """h-4: Hook freshness is judged by the installed shim's content, not its mtime."""

    def _layout(self, tmp: str) -> tuple[Path, Path]:
        tmp_path = Path(tmp)
        worktree = tmp_path / "worktree"
        worktree.mkdir()
        config_path = worktree / ".pre-commit-config.yaml"
        config_path.write_text("repos: []", encoding="utf-8")
        hook_path = tmp_path / "common-git" / "hooks" / "pre-commit"
        return hook_path, config_path

    def test_correct_shim_older_than_config_is_fresh(self):
        """The false positive: a correct shim older than the config must pass.

        Every freshly created linked worktree checks out a config newer than the
        one shared hook in the common git dir. The shim reads its config at run
        time, so its age says nothing about staleness; a re-install produces a
        byte-identical file.
        """
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            _write_precommit_shim(hook_path, sys.executable)
            _age_hook_behind_config(hook_path, config_path)
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertTrue(
            result,
            msg=(
                "A correct pre-commit shim older than the config must be fresh "
                f"(the linked-worktree false positive). Got: {result}"
            ),
        )

    def test_correct_shim_newer_than_config_is_fresh(self):
        """A correct shim newer than the config is fresh as well."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            _write_precommit_shim(hook_path, sys.executable)
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertTrue(result, msg=f"Expected a correct shim to be fresh. Got: {result}")

    def test_shim_resolves_config_against_leafcutter_project_root(self):
        """When the resolved config is .leafcutter/pre-commit-config.yaml, the
        shim's --config= is resolved against the project root (its parent's parent),
        not against .leafcutter/."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, direct_config = self._layout(tmp)
            leafcutter_dir = direct_config.parent / ".leafcutter"
            leafcutter_dir.mkdir()
            leafcutter_config = leafcutter_dir / "pre-commit-config.yaml"
            leafcutter_config.write_text("repos: []", encoding="utf-8")
            _write_precommit_shim(hook_path, sys.executable)
            _age_hook_behind_config(hook_path, leafcutter_config)
            result = _vpa.check_hook_freshness(hook_path, leafcutter_config)
        self.assertTrue(
            result,
            msg=(
                "Expected the shim's --config=.pre-commit-config.yaml to resolve "
                f"against the project root above .leafcutter/. Got: {result}"
            ),
        )

    def test_non_shim_hook_is_stale(self):
        """A hook that is not a pre-commit-generated shim fails, even when newer."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            hook_path.parent.mkdir(parents=True)
            hook_path.write_text("#!/bin/sh\n# runs pre-commit, honest\nexit 0\n", encoding="utf-8")
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertFalse(result, msg=f"Expected a non-shim hook to fail freshness. Got: {result}")

    def test_shim_naming_missing_config_is_stale(self):
        """A shim whose --config= names a file absent from the project root fails."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            _write_precommit_shim(
                hook_path, sys.executable, config_arg="config/gone-pre-commit.yaml"
            )
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertFalse(
            result,
            msg=f"Expected a shim naming a missing config to fail freshness. Got: {result}",
        )

    def test_shim_with_missing_interpreter_is_stale(self):
        """A shim whose INSTALL_PYTHON interpreter does not exist fails."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            missing_python = str(Path(tmp) / "removed-venv" / "bin" / "python")
            _write_precommit_shim(hook_path, missing_python)
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertFalse(
            result,
            msg=(
                "Expected a shim with a missing INSTALL_PYTHON interpreter to fail "
                f"freshness. Got: {result}"
            ),
        )

    def test_shim_for_other_hook_type_is_stale(self):
        """A shim generated for another hook type, installed as pre-commit, fails."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)
            _write_precommit_shim(hook_path, sys.executable, hook_type="pre-push")
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertFalse(
            result,
            msg=f"Expected a pre-push shim to fail pre-commit freshness. Got: {result}",
        )

    def test_hook_missing_config_present(self):
        """A missing hook with a present config is a fail-closed state (not installed)."""
        # covers: BO-1700h-4
        with tempfile.TemporaryDirectory() as tmp:
            hook_path, config_path = self._layout(tmp)  # hook intentionally never created
            result = _vpa.check_hook_freshness(hook_path, config_path)
        self.assertFalse(
            result, msg=f"Expected check_hook_freshness to fail when the hook is absent. Got: {result}"
        )


if __name__ == "__main__":
    unittest.main()
