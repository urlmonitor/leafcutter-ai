def test_briefing_lists_declared_abilities_for_former_older_field_specialists(tmp_path):
    # covers: AR-400e-1-i
    # angle: criterion
    """Over a copy of the real tree, the briefing of each former older-field-only specialist
    lists exactly its frontmatter ``skills:`` ids (descriptive_only never listed), and the
    registry validation's examined set holds exactly those ids for it too. Red while the
    committed registry carries those abilities only in skills_used."""
    older, _newer = H.snapshot_populations()
    root = H.lean_root(tmp_path)
    decl = H.declared_ids(root)
    assert set(older) <= set(decl) and all(decl[a] for a in older), "population must be declared specialists"
    expected = {a: decl[a] for a in older}
    problems = H.mismatches("briefing", H.view_briefing(root, older), expected)
    validation = H.view_validation(root, tmp_path)
    problems += [m for m in H.mismatches("validation", validation, expected) if "examined" not in m]
    assert not problems, f"{len(problems)} problem(s):\n" + "\n".join(problems)


class TestPlantedUnresolvableId(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.base = Path(self._tmp.name)

    def _validate_after_declaring(self, agent: str, skill_id: str, name: str) -> tuple[int, str]:
        root = H.lean_root(self.base, name=name)
        H.declare_extra(root, agent, skill_id)
        self.assertEqual(H.run_hook(root).returncode, 0)
        return H.view_validation_errors(root)

    def test_planted_unresolvable_id_fails_validation_naming_the_specialist(self):
        # covers: AR-400e-1-i
        # angle: failure
        """A nonexistent id added to a former older-field-only specialist's DECLARATION, the
        registry regenerated by the hook, makes the build's registry validation fail with ONE
        extra error naming that specialist and the id. Control (same specialist, a REAL
        undeclared skill): no extra error -- so the failure is the unresolvable id, not the
        planting machinery. Red today: the hook keeps that specialist in skills_used, so the
        id never reaches the field the validation resolves."""
        older, _ = H.snapshot_populations()
        agent = older[0]
        base_root = H.lean_root(self.base, name="baseline")
        self.assertEqual(H.run_hook(base_root).returncode, 0)
        base_errors, _ = H.view_validation_errors(base_root)
        real_extra = next(p.name for p in sorted((base_root / "templates" / "skills").iterdir())
                          if (p / "SKILL.md").is_file() and p.name not in H.declared_ids(base_root)[agent])
        ok_errors, ok_out = self._validate_after_declaring(agent, real_extra, "control")
        self.assertEqual(ok_errors, base_errors, ok_out)
        bad_errors, bad_out = self._validate_after_declaring(agent, H.GHOST, "ghost")
        # one finding = one line naming the specialist AND the id (its hint lines name only the id)
        ghost_lines = [ln for ln in bad_out.splitlines() if H.GHOST in ln and f"'{agent}'" in ln]
        self.assertEqual(len(ghost_lines), 1, f"expected one finding for {H.GHOST}: {bad_out[-1500:]}")
        self.assertEqual(bad_errors, base_errors + 1, bad_out[-1500:])

    def test_deleting_retired_field_from_fixture_registry_changes_neither_view(self):
        # covers: AR-400e-1-i
        # angle: discrimination
        """Wrong version caught: a view that falls back to / unions the retired skills_used.
        Two copies of the real tree, one with skills_used hand-deleted: the briefing markdown of
        every older- and newer-field specialist and the validation output are byte-identical.
        Paired positive (else both sides are vacuously empty): the briefing and validation show
        each former older-field specialist's declared abilities."""
        older, newer = H.snapshot_populations()
        with_field = H.lean_root(self.base, name="with")
        without = H.lean_root(self.base, name="without")
        H.strip_retired(without)
        agents = older + newer
        for agent in agents:  # the copies differ in their directory name only; normalise that
            first = H.briefing_markdown(with_field, agent).replace(str(with_field), "<ROOT>")
            second = H.briefing_markdown(without, agent).replace(str(without), "<ROOT>")
            self.assertEqual(first, second, agent)
        self.assertEqual(H.view_validation_errors(with_field), H.view_validation_errors(without))
        decl = H.declared_ids(without)
        expected = {a: decl[a] for a in older}
        self.assertEqual(H.mismatches("briefing", H.view_briefing(without, older), expected), [])
        sterile = H.view_validation(without, self.base)
        self.assertEqual([m for m in H.mismatches("validation", sterile, expected) if "examined" not in m], [])


