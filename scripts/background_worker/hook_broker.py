"""Trusted Git hook trampoline; only its bubblewrap child executes project code.

Real Git metadata is read-only. Hooks use disposable index/object writes and a
changed staged tree forces another implementation/check cycle before commit.
"""

from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

if __package__:
    from .execution_boundary import ExecutorError, local_environment, safe_output
    from .bootstrap import PROTECTED_PATHS
else:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from background_worker.execution_boundary import ExecutorError, local_environment, safe_output
    from background_worker.bootstrap import PROTECTED_PATHS


def git(cwd, *args, env=None):
    try:
        result = subprocess.run(
            ["git", "-c", "core.fsmonitor=false", "--no-optional-locks", *args],
            cwd=cwd,
            env=env,
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise ExecutorError("Cannot resolve a hook's owned Git context") from exc
    return result.stdout.strip()


def bubblewrap_command(workspace, repo, common, git_dir, scratch, hook, runtime_paths):
    """Start from an empty namespace, admitting only explicit runtime/project paths."""
    command = ["bwrap", "--die-with-parent", "--new-session", "--unshare-all", "--cap-drop", "ALL"]
    mounts = []
    for value in (
        "/usr",
        "/bin",
        "/sbin",
        "/lib",
        "/lib64",
        "/etc/ld.so.cache",
        "/etc/passwd",
        "/etc/group",
        sys.prefix,
        sys.base_prefix,
        *runtime_paths,
    ):
        path = Path(value)
        if path.exists() and str(path) not in mounts:
            if path.resolve() == Path("/"):
                raise ExecutorError("A hook runtime mount cannot expose the host root")
            mounts.append(str(path))
            command += ["--ro-bind", str(path), str(path)]
    command += ["--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp"]
    # During worktree creation reference hooks run in the source repo; that
    # checkout is admitted read-only, never as another writable workspace.
    if workspace == repo:
        command += ["--ro-bind", str(repo), str(repo)]
    else:
        command += ["--bind", str(workspace), str(workspace)]
    for relative in PROTECTED_PATHS:
        path = workspace / relative
        if path.is_symlink():
            raise ExecutorError("Protected hook runtime cannot be a symlink")
        if path.exists():
            command += ["--ro-bind", str(path), str(path)]
    for path in dict.fromkeys((common, git_dir)):
        command += ["--ro-bind", str(path), str(path)]
    hook_source = hook
    if hook_command(hook)[0] == "/bin/bash":
        hook_source = scratch / "generated-hook"
        try:
            hook_source.write_bytes(hook.read_bytes().replace(b"\r\n", b"\n"))
        except OSError as exc:
            raise ExecutorError("Cannot prepare generated hook line endings") from exc
    command += ["--ro-bind", str(hook_source), str(hook)]
    dotgit = workspace / ".git"
    if dotgit.exists():
        command += ["--ro-bind", str(dotgit), str(dotgit)]
    command += [
        "--bind",
        str(scratch),
        str(scratch),
        "--remount-ro",
        "/tmp",
        "--chdir",
        str(workspace),
        "--",
        str(hook),
    ]
    if hook_source != hook:
        # Preserve $0/HERE at the original path; prevent writes through its scratch alias.
        position = command.index("--chdir")
        command[position:position] = ["--ro-bind", str(hook_source), str(hook_source)]
    return command


def hook_command(hook):
    """Recognize only pre-commit's Windows-generated Bash shim signature."""
    try:
        header = hook.read_bytes()[:512].replace(b"\r\n", b"\n")
    except OSError as exc:
        raise ExecutorError("Cannot inspect the installed Git hook") from exc
    signature = b"#!/bin/sh\n#!/usr/bin/env bash\n# File generated by pre-commit:"
    return ["/bin/bash", str(hook)] if header.startswith(signature) else [str(hook)]


def staged_tree(command, env, cwd):
    """Inspect even a hook-written index inside the same namespace boundary."""
    try:
        result = subprocess.run(
            [*command[:-1], "git", "write-tree"],
            env=env,
            cwd=cwd,
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise ExecutorError("Cannot validate the hook's isolated staging tree") from exc
    return result.stdout.strip()


def execute_hook(manifest, hook_name, arguments):
    cwd = Path.cwd().resolve()
    repo, owned = Path(manifest["repo"]).resolve(), Path(manifest["workspace"]).resolve()
    if cwd not in {repo, owned}:
        raise ExecutorError("Hook working directory does not belong to this coordinator invocation")
    hook = Path(manifest["hooks"][hook_name]).resolve(strict=True)
    common = Path(git(cwd, "rev-parse", "--path-format=absolute", "--git-common-dir"))
    git_dir = Path(git(cwd, "rev-parse", "--absolute-git-dir"))
    index = Path(git(cwd, "rev-parse", "--path-format=absolute", "--git-path", "index"))
    try:
        with tempfile.TemporaryDirectory(prefix="leafcutter-hook-work-") as temporary:
            scratch = Path(temporary)
            alternate_objects = common / "objects"
            (scratch / "objects").mkdir()
            (scratch / "home").mkdir()
            runtime_paths = list(manifest["runtime_read_paths"])
            prepared_cache = manifest.get("pre_commit_cache")
            if prepared_cache:
                shutil.copytree(prepared_cache, scratch / "pre-commit", symlinks=True)
                runtime_paths.append(prepared_cache)
            if index.is_file():
                shutil.copyfile(index, scratch / "index")
            env = local_environment()
            env.update(
                {
                    "HOME": str(scratch / "home"),
                    "XDG_CACHE_HOME": str(scratch / "cache"),
                    "PRE_COMMIT_HOME": str(scratch / "pre-commit"),
                    "TMPDIR": str(scratch),
                    "GIT_DIR": str(git_dir),
                    "GIT_COMMON_DIR": str(common),
                    "GIT_WORK_TREE": str(cwd),
                    "GIT_INDEX_FILE": str(scratch / "index"),
                    "GIT_OBJECT_DIRECTORY": str(scratch / "objects"),
                    "GIT_ALTERNATE_OBJECT_DIRECTORIES": str(alternate_objects),
                    "GIT_CONFIG_NOSYSTEM": "1",
                    "GIT_CONFIG_GLOBAL": "/dev/null",
                }
            )
            command = bubblewrap_command(cwd, repo, common, git_dir, scratch, hook, runtime_paths)
            before_tree = staged_tree(command, env, cwd) if (scratch / "index").exists() else None
            arguments = list(arguments)
            message = None
            if hook_name in {"prepare-commit-msg", "commit-msg"} and arguments:
                original = (cwd / arguments[0]).resolve()
                if original != (git_dir / "COMMIT_EDITMSG").resolve():
                    raise ExecutorError(
                        "Commit message hook argument escaped the owned Git metadata"
                    )
                message = scratch / "COMMIT_EDITMSG"
                shutil.copyfile(original, message)
                arguments[0] = str(message)
            stdin = (
                sys.stdin.buffer.read()
                if hook_name
                in {
                    "pre-push",
                    "pre-receive",
                    "post-receive",
                    "post-rewrite",
                    "reference-transaction",
                }
                else b""
            )
            result = subprocess.run(
                [*command[:-1], *hook_command(hook), *arguments],
                input=stdin,
                env=env,
                cwd=cwd,
                capture_output=True,
                timeout=600,
            )
            stdout = safe_output(result.stdout.decode("utf-8", errors="replace"))
            stderr = safe_output(result.stderr.decode("utf-8", errors="replace"))
            sys.stdout.write(stdout)
            sys.stderr.write(stderr)
            if result.returncode:
                raise ExecutorError(
                    f"Hook exited {result.returncode}; namespace execution refused or check failed"
                )
            after_tree = staged_tree(command, env, cwd) if (scratch / "index").exists() else None
            if before_tree != after_tree:
                raise ExecutorError(
                    "Hook changed the staged tree; re-run project checks and stage through the coordinator"
                )
            if hook_name in {"pre-commit", "prepare-commit-msg", "commit-msg", "pre-push"}:
                changed = subprocess.run(
                    [*command[:-1], "git", "diff", "--quiet", "--"],
                    env=env,
                    cwd=cwd,
                    capture_output=True,
                    timeout=30,
                )
                if changed.returncode:
                    raise ExecutorError(
                        "Hook changed tracked worktree contents; revalidation required before commit"
                    )
            if message is not None:
                # Only this exact per-worktree message file is imported, never
                # the hook's scratch index, object store, refs or configuration.
                if message.is_symlink() or not message.is_file():
                    raise ExecutorError("Hook commit message is not a regular file")
                original.write_bytes(message.read_bytes())
    except (OSError, subprocess.SubprocessError) as exc:
        raise ExecutorError(
            "Hook sandbox failed before a trustworthy outcome was available"
        ) from exc


def main():
    manifest = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    hook_name = sys.argv[2]
    record = {"hook": hook_name, "passed": False, "reason": ""}
    try:
        execute_hook(manifest, hook_name, sys.argv[3:])
        record["passed"] = True
    except (ExecutorError, OSError, ValueError, KeyError) as exc:
        record["reason"] = safe_output(str(exc))
        sys.stderr.write(record["reason"] + "\n")
    try:
        with Path(manifest["outcomes"]).open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(record) + "\n")
    except OSError as exc:
        raise ExecutorError(
            "Cannot persist Git hook outcome; coordinator must not accept it"
        ) from exc
    return 0 if record["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
