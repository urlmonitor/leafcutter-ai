"""
MODULE: unit_tests/commit_guardian/test_ge_134a_3.py
COVERS: GE-134a-3 -- the stated measurement rule tells the author that a
    decision-history block is not counted, where it starts and ends, and
    that ordinary comments still count

GOAL: The seven test_spec descriptors of GE-134a-3. The stated rule is
    describe_measurement_rule() (printed on the refusal's Measures: line)
    and the MEASUREMENT RULE sentence of the shipped commit_guardian.json's
    file_size._comment. Pinned vocabulary (_ge_134a_fixture.py):
    the not-counted regexes defined at the top of this file.

RED TODAY: describe_measurement_rule() probes only triple-quoted strings,
    block comments and hash comments; it says nothing about a
    decision-history block, and the shipped config still says every hash
    comment line is counted.

DECISION HISTORY
- 2026-10-21 [test-writer/GE-134a-3]: Initial authoring.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _ge_127d_2_fixture as d2  # noqa: E402
import _ge_134a_fixture as fx  # noqa: E402

_NOT_COUNTED_COMMENTS_RE = re.compile(r"not count[^;]*\bcomments\b", re.IGNORECASE)
_NOT_COUNTED_STANDALONE_RE = re.compile(r"not count[^;]*standalone strings", re.IGNORECASE)
_OLD_HASH_SENTENCE ="every remaining line -- including blank lines and hash comment lines -- is counted"


@pytest.fixture()
def ratchet():
    return fx.load_ratchet()


def _refusal_output(root: Path) -> str:
    """Stage the GE-134a-1 Python example under a limit of 50 and return the
    fixture copy of check_file_size.py's refusal output."""
    d2.build_fixture_tree(root, line_limit=50, checked_extensions=[".py"])
    result = fx.stage_and_check(root, "src/example.py", fx.python_example())
    output = d2.combined_output(result)
    assert result.returncode == 1, output
    return output


def test_ge_134a_3_stated_rule_says_a_history_block_is_not_counted(ratchet):
    # covers: GE-134a-3
    # angle: criterion
    """GE-127d-3 (2026-10-21) supersedes the dedicated history sentence: a decision-history
    block, whether line comments or a trailing string, is covered by the general statement
    that comments of every style and standalone strings are not counted."""
    rule = ratchet.describe_measurement_rule()
    assert _NOT_COUNTED_COMMENTS_RE.search(rule), rule
    assert _NOT_COUNTED_STANDALONE_RE.search(rule), rule


def test_ge_134a_3_stated_rule_follows_the_rule_in_force(ratchet, monkeypatch):
    # covers: GE-134a-3
    # angle: criterion
    """The statement is generated by probing the rule in force: present under the real
    rule, gone once count_content_lines is rebound to the pre-change rule."""
    assert _NOT_COUNTED_COMMENTS_RE.search(ratchet.describe_measurement_rule())

    monkeypatch.setattr(ratchet, "count_content_lines", lambda content, *a, **k: fx.pre_change_count(content))
    rebound_rule = ratchet.describe_measurement_rule()
    assert "comments of every style" not in rebound_rule, rebound_rule

def test_ge_134a_3_refusal_measures_line_states_the_history_exclusion(tmp_path):
    # covers: GE-134a-3
    # angle: reachability
    """The Measures: line of a real refusal from the fixture copy of
    check_file_size.py states that comments and standalone strings (which cover any
    decision-history block) are not counted."""
    measures = d2.extract_measures_line(_refusal_output(tmp_path))
    assert measures is not None
    assert _NOT_COUNTED_COMMENTS_RE.search(measures), measures
    assert _NOT_COUNTED_STANDALONE_RE.search(measures), measures


def test_ge_134a_3_published_config_rule_states_the_history_exclusion():
    # covers: GE-134a-3
    # angle: criterion
    """The MEASUREMENT RULE sentence of the shipped file_size._comment says comments and
    standalone strings (so any decision-history block) are not counted, and no longer says
    every hash comment line is counted."""
    file_size = json.loads(fx.SHIPPED_CONFIG.read_text(encoding="utf-8"))["file_size"]
    assert "commit_guardian.json" in file_size["published_rule_surfaces"]
    comment = file_size["_comment"]
    assert "MEASUREMENT RULE" in comment
    rule_text = comment.split("MEASUREMENT RULE", 1)[1]
    assert _NOT_COUNTED_COMMENTS_RE.search(rule_text), rule_text
    assert _NOT_COUNTED_STANDALONE_RE.search(rule_text), rule_text
    assert _OLD_HASH_SENTENCE not in rule_text


def test_ge_134a_3_stated_rule_names_where_the_block_starts_and_ends(ratchet):
    # covers: GE-134a-3
    # angle: criterion
    """GE-127d-3 (2026-10-21) removes the start/end vocabulary: with no block concept left,
    the statement does not depend on a heading, a rule line or where a block ends -- it
    names no 'DECISION HISTORY' heading and no position, and instead covers every comment
    style and every standalone string wherever they stand."""
    rule = ratchet.describe_measurement_rule()
    lowered = rule.lower()
    assert "decision history" not in lowered, rule
    assert "whole text" not in lowered and "directly above" not in lowered, rule
    assert "comments of every style" in lowered, rule
    assert "standalone strings" in lowered, rule


def test_ge_134a_3_stated_rule_says_ordinary_comments_still_count(ratchet):
    # covers: GE-134a-3
    # angle: criterion
    """GE-127d-3 (2026-10-21): the stated rule says ordinary comments are NOT counted
    either -- no counting clause mentions comments, and blank lines are not counted."""
    rule = ratchet.describe_measurement_rule()
    counted_clauses = [c for c in rule.lower().split(";") if "count" in c and "not count" not in c]
    assert not any("comment" in c for c in counted_clauses), rule
    assert re.search(r"not count[^;]*blank lines", rule, re.IGNORECASE), rule


def test_ge_134a_3_applying_the_stated_rule_by_hand_gives_80(tmp_path):
    # covers: GE-134a-3
    # angle: criterion
    """An independent counter applying the stated rule (no comment, no standalone string, no
    blank line) to the GE-134a-1 Python example arrives at 64 -- the length the check quotes
    (the test name keeps the 80 of the pre-GE-127d-3 rule)."""
    output = _refusal_output(tmp_path)
    measures = d2.extract_measures_line(output)
    assert _NOT_COUNTED_COMMENTS_RE.search(measures or ""), measures
    by_hand = fx.independent_count(fx.python_example())
    assert by_hand == 64, output
    assert d2.parse_lines_and_limit(output) == (by_hand, 50), output
