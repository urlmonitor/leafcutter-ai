"""INF-700b-2 -- a template that names a skill which does not exist is refused by the
repository's own gating (TDD red phase, written BEFORE the coder runs).

Decisions recorded at test-writing time (architect-review 2026-10-22 plus the dispatcher's
answers to its open questions):

1. The commit-time gate is the EXISTING ``check-agent-registry`` hook, widened from
   ``templates/agents/`` to any staged ``templates/**/*.md``. There is no separate
   ``check-skill-refs`` hook. Its failure banner must name the skill-reference failure (not only
   "agent_registry.json validation failed") and every error line names the template path and the
   unresolved skill.
2. The dead standalone CLI ``scripts/check_skill_refs.py`` ``main()`` must use
   ``ability_reference_verdict`` (the verdict the build uses): exit 0 on the current tree
   (``provided_by: project`` skills of sql-coder accepted) and non-zero naming file + skill on a
   dangling reference.
3. The CI path is the ``build.py`` step ``test-shard`` runs before pytest; ``Test suite (pytest)``
   is a required check of Ruleset ``require-ci-lint`` and aggregates ``test-shard``, so the CI
   refusal needs no repo-admin action.

Doors: every hook test runs the hook ENTRY exactly as the generated pre-commit config spells it
(entry string read from a config generated by ``build_precommit_config`` from the shipped
manifest, never by importing the hook function) as a real subprocess, with cwd at a REAL temporary
git repository whose index holds the staged template, laid out like a deployed install
(``.leafcutter/scripts/commit_guardian/`` = the shipped hook directory; the package at the
project root). Fixtures are verbatim copies of the real ``scripts/``, ``config/``, ``templates/``
trees; the only mutation is one appended sentence.

What the CI/build door test here proves, exactly (no second 60 s ``build.py`` spawn is added):
``registry_validator.py`` is run directly, as a CLI, on a mutated copy of the package; ``ci.yml``
is read structurally (step order and ``needs``), not executed. It does NOT exercise build.py's
abort path for the ``templates/skills/`` surface: that is exercised by
``test_inf_700b_2_ci.py`` (real ``build.py --target-dir`` runs over a private copy). Whether
``Test suite (pytest)`` is a required check was VERIFIED on 2026-10-23 by ``gh api
repos/urlmonitor/leafcutter-ai/rules/branches/main``, which lists the required checks "Lint
(ruff)", "Component vocab style (components.json)", "Proof-of-done coverage check (BO-2500b)",
"Changelog entry present", "AC store valid" and "Test suite (pytest)". No unit test asserts it:
CI has no admin token.
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
SHIPPED_HOOK_DIR = REPO_ROOT / "templates" / "scripts" / "commit_guardian"
CI_YML = REPO_ROOT / ".github" / "workflows" / "ci.yml"

HOOK_ID = "check-agent-registry"
DANGLING = "no-such-skill"
DANGLING_SENTENCE = f"Load the `{DANGLING}` skill before you continue."
VALID_SENTENCE = "This paragraph describes the surrounding procedure and names no skill."
SKILL_TEMPLATE = "templates/skills/signoff/SKILL.md"
AGENT_TEMPLATE = "templates/agents/research-agent.md"

_TIMEOUT = 180
_ENV = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}

# Runs in a FRESH interpreter so the generated config is produced by the real generator, from the
# shipped manifest, exactly as build.py's pre-commit phase does.
_GENERATE_CONFIG = (
    "import sys\n"
    "from pathlib import Path\n"
    "sys.path.insert(0, sys.argv[1])\n"
    "from build_precommit import build_precommit_config\n"
    "build_precommit_config(Path(sys.argv[2]), {'output_root': '.leafcutter'}, False, True)\n"
)


def _run(cmd: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=_TIMEOUT,
                          env=_ENV, check=False)


def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args], cwd=str(repo),
                   check=True, capture_output=True, env=_ENV)


def generate_precommit_config(dest: Path) -> dict:
    """Generate the pre-commit config from the shipped manifest in a fresh process; return it parsed."""
    dest.mkdir(parents=True, exist_ok=True)
    cp = subprocess.run([sys.executable, "-c", _GENERATE_CONFIG, str(REPO_ROOT / "scripts"), str(dest)],
                        capture_output=True, text=True, timeout=_TIMEOUT, env=_ENV, check=False)
    assert cp.returncode == 0, cp.stderr
    produced = sorted(p for p in dest.iterdir() if p.name.endswith("pre-commit-config.yaml"))
    assert produced, f"generator wrote no pre-commit config into {dest}: {cp.stdout} {cp.stderr}"
    return yaml.safe_load(produced[0].read_text(encoding="utf-8"))


def hook_stanza(config: dict, hook_id: str = HOOK_ID) -> dict:
    stanzas = [h for repo in config["repos"] for h in repo["hooks"] if h.get("id") == hook_id]
    assert len(stanzas) == 1, f"expected exactly one {hook_id} stanza, found {len(stanzas)}"
    return stanzas[0]


def _copy(src: Path, dst: Path) -> None:
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__"))


class _HookRepoBase(unittest.TestCase):
    """One deployed-layout git repo per class (copy once, reset per test)."""

    @classmethod
    def setUpClass(cls) -> None:
        cls._tmp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls._tmp.cleanup)
        base = Path(cls._tmp.name)
        cls.config = generate_precommit_config(base / "generated")
        cls.entry = hook_stanza(cls.config)["entry"]
        cls.repo = base / "project"
        cls.repo.mkdir()
        for name in ("scripts", "config", "templates"):
            _copy(REPO_ROOT / name, cls.repo / name)
        _copy(SHIPPED_HOOK_DIR, cls.repo / ".leafcutter" / "scripts" / "commit_guardian")
        (cls.repo / ".build_manifest.json").write_text('{"package_root": ""}', encoding="utf-8")
        _git(cls.repo, "init", "-q")
        _git(cls.repo, "add", "-A")
        _git(cls.repo, "commit", "-q", "-m", "baseline")

    def setUp(self) -> None:
        self.addCleanup(self._restore)

    def _restore(self) -> None:
        _git(self.repo, "reset", "-q", "--hard")
        _git(self.repo, "clean", "-fdq")

    def stage_append(self, rel: str, sentence: str) -> None:
        path = self.repo / rel
        text = path.read_text(encoding="utf-8")
        path.write_text(text.rstrip("\n") + "\n\n" + sentence + "\n", encoding="utf-8")
        _git(self.repo, "add", rel)

    def run_hook_entry(self) -> subprocess.CompletedProcess:
        """Run the entry string from the generated config, verbatim but for the interpreter name."""
        argv = shlex.split(self.entry)
        self.assertEqual(argv[0], "python", self.entry)
        argv[0] = sys.executable
        return _run(argv, self.repo)


class TestPrecommitHookGate(_HookRepoBase):
    def test_precommit_hook_refuses_a_commit_introducing_a_dangling_skill_reference(self):
        # covers: INF-700b-2
        # angle: reachability
        """A staged templates/skills/ markdown file tells the reader to load a skill that is not
        shipped. The generated hook entry exits non-zero, a banner line names the skill-reference
        failure (not only "agent_registry.json validation failed"), and one error line names the
        template path AND the skill. Red today: the hook scopes itself to templates/agents/ and
        returns 0 for any other staged path."""
        self.stage_append(SKILL_TEMPLATE, DANGLING_SENTENCE)
        cp = self.run_hook_entry()
        out = cp.stdout + "\n" + cp.stderr
        self.assertNotEqual(cp.returncode, 0, f"a dangling skill reference was not refused: {out}")
        named = [ln for ln in out.splitlines() if SKILL_TEMPLATE in ln and DANGLING in ln]
        self.assertTrue(named, f"no error line names both {SKILL_TEMPLATE} and {DANGLING}: {out}")
        banner = [ln for ln in out.splitlines()
                  if ln.startswith(f"[{HOOK_ID}]") and re.search(r"skill[- ]reference", ln, re.I)]
        self.assertTrue(banner, f"banner does not name the skill-reference failure: {out}")

    def test_precommit_hook_refuses_a_dangling_reference_in_another_template_surface(self):
        # covers: INF-700b-2
        # angle: failure
        """Same gate, a template that is neither under agents/ nor skills/ (first shipped
        templates/commands markdown file): the scope is every staged templates/**/*.md. Red today."""
        rel = sorted(p.relative_to(self.repo).as_posix()
                     for p in (self.repo / "templates" / "commands").glob("*.md"))[0]
        self.stage_append(rel, DANGLING_SENTENCE)
        cp = self.run_hook_entry()
        out = cp.stdout + "\n" + cp.stderr
        self.assertNotEqual(cp.returncode, 0, out)
        self.assertTrue([ln for ln in out.splitlines() if rel in ln and DANGLING in ln],
                        f"no error line names {rel} and {DANGLING}: {out}")

    def test_precommit_hook_still_refuses_a_dangling_reference_in_templates_agents_control(self):
        # covers: INF-700b-2
        # angle: failure
        """GREEN CONTROL (already caught today): the same sentence staged under templates/agents/
        is refused naming path and skill. Pins that widening the scope does not lose the old one
        and that test 1's red is about the scope, not about the sentence."""
        self.stage_append(AGENT_TEMPLATE, DANGLING_SENTENCE)
        cp = self.run_hook_entry()
        out = cp.stdout + "\n" + cp.stderr
        self.assertNotEqual(cp.returncode, 0, out)
        self.assertTrue([ln for ln in out.splitlines() if AGENT_TEMPLATE in ln and DANGLING in ln],
                        f"no error line names {AGENT_TEMPLATE} and {DANGLING}: {out}")

    def test_precommit_hook_passes_over_a_consistent_template_tree(self):
        # covers: INF-700b-2
        # angle: criterion
        """The same invocation over the real, consistent tree with a harmless templates/skills/
        edit (no skill named) exits zero and prints no violation. Control row for the refusing
        tests above, which use the identical repo and entry. Green today and must stay green: a
        widened hook that blocks every templates/ edit fails here."""
        self.stage_append(SKILL_TEMPLATE, VALID_SENTENCE)
        cp = self.run_hook_entry()
        out = cp.stdout + "\n" + cp.stderr
        self.assertEqual(cp.returncode, 0, out)
        self.assertNotIn(DANGLING, out)
        self.assertNotIn("validation failed", out)

    def test_precommit_hook_passes_over_a_valid_skill_reference(self):
        # covers: INF-700b-2
        # angle: boundary
        """A staged templates/skills/ edit that DOES name a shipped skill (`signoff`, with the
        word skill and a strong verb, so the recogniser counts it) resolves and passes: the
        widened hook must distinguish resolved from unresolved, not refuse any reference."""
        self.assertTrue((self.repo / "templates" / "skills" / "signoff").is_dir())
        self.stage_append(SKILL_TEMPLATE, "Load the `signoff` skill before you continue.")
        cp = self.run_hook_entry()
        self.assertEqual(cp.returncode, 0, cp.stdout + "\n" + cp.stderr)


class TestCiPathBuildStep(_HookRepoBase):
    def test_ci_job_invokes_the_skill_reference_gate_and_fails_the_build(self):
        # covers: INF-700b-2
        # angle: reachability
        """Structural + validator proof only. (a) ci.yml is read as YAML: the test-shard job has
        a `python scripts/build.py --target-dir .` step BEFORE its pytest step, and the
        `Test suite (pytest)` job needs test-shard (this reads the workflow; it runs nothing in
        CI). (b) registry_validator.py, the validator build.py calls, is run directly as a CLI
        over a package copy with a dangling reference in templates/skills/ and exits non-zero
        naming the template path and the skill. build.py's own abort path is NOT exercised here
        for the skills surface (see the module docstring); no build is spawned here -- the real
        build.py door is test_inf_700b_2_ci.py."""
        wf = yaml.safe_load(CI_YML.read_text(encoding="utf-8"))
        shard = wf["jobs"]["test-shard"]
        runs = [str(s.get("run", "")) for s in shard["steps"]]
        build_idx = [i for i, r in enumerate(runs) if re.search(r"python\s+scripts/build\.py\s+--target-dir\s+\.", r)]
        pytest_idx = [i for i, r in enumerate(runs) if "pytest" in r]
        self.assertTrue(build_idx and pytest_idx, runs)
        self.assertLess(min(build_idx), min(pytest_idx), "build must run before pytest")
        gate = wf["jobs"]["test"]
        self.assertEqual(gate["name"], "Test suite (pytest)")
        needs = gate["needs"]
        self.assertIn("test-shard", [needs] if isinstance(needs, str) else needs)

        self.stage_append(SKILL_TEMPLATE, DANGLING_SENTENCE)
        cp = _run([sys.executable, str(self.repo / "scripts" / "registry_validator.py")], self.repo)
        out = cp.stdout + "\n" + cp.stderr
        self.assertNotEqual(cp.returncode, 0, out)
        self.assertTrue([ln for ln in out.splitlines() if SKILL_TEMPLATE in ln and DANGLING in ln],
                        f"build validator does not name {SKILL_TEMPLATE} and {DANGLING}: {out}")


class TestGeneratedConfig(unittest.TestCase):
    def test_generated_precommit_config_contains_the_gate_after_a_build(self):
        # covers: INF-700b-2
        # angle: deployed
        """The config the generator emits from the shipped manifest carries check-agent-registry
        with NO files: filter (so a commit staging only templates/skills/** still invokes it),
        pass_filenames false, and an entry that runs the hook through run_hook.py. Green today
        (the stanza already has no filter); it goes red if the widening is done by adding a
        narrower files: regex instead of widening the hook's own scope."""
        with tempfile.TemporaryDirectory() as tmp:
            stanza = hook_stanza(generate_precommit_config(Path(tmp)))
        self.assertNotIn("files", stanza)
        self.assertIs(stanza.get("pass_filenames"), False)
        self.assertIn("commit_guardian/run_hook.py", stanza["entry"])
        self.assertIn("commit_guardian/check_agent_registry.py", stanza["entry"])
        self.assertIn("pre-commit", stanza["stages"])


class TestStandaloneCli(_HookRepoBase):
    CLI = REPO_ROOT / "scripts" / "check_skill_refs.py"

    def test_check_skill_refs_cli_exits_zero_on_the_current_tree(self):
        # covers: INF-700b-2
        # angle: reachability
        """`python3 scripts/check_skill_refs.py` over the repository's own tree exits 0. Red
        today: the CLI ignores `provided_by: project`, so it exits 1 on sql-coder's `postgres`
        and `sql-test`; fixed by making main() use ability_reference_verdict."""
        cp = _run([sys.executable, str(self.CLI)], REPO_ROOT)
        self.assertEqual(cp.returncode, 0, cp.stdout + "\n" + cp.stderr)

    def test_check_skill_refs_cli_exits_nonzero_naming_file_and_skill_on_a_mutated_copy(self):
        # covers: INF-700b-2
        # angle: failure
        """Over a package copy with one dangling reference the CLI exits non-zero and names the
        template file and `no-such-skill`, and it does NOT report sql-coder's project-supplied
        skills (`postgres`, `sql-test`) as dangling -- the discriminating half: a CLI that merely
        exits 1 because of those two (today's behaviour) would fail this."""
        self.stage_append(SKILL_TEMPLATE, DANGLING_SENTENCE)
        cp = _run([sys.executable, str(self.CLI), "--repo-root", str(self.repo)], REPO_ROOT)
        out = cp.stdout + "\n" + cp.stderr
        self.assertNotEqual(cp.returncode, 0, out)
        self.assertTrue([ln for ln in out.splitlines() if SKILL_TEMPLATE in ln and DANGLING in ln]
                        or (SKILL_TEMPLATE in out and DANGLING in out), out)
        for provided_by_project in ("postgres", "sql-test"):
            self.assertNotIn(f"'{provided_by_project}'", out)
            self.assertNotIn(f"`{provided_by_project}`", out)
            self.assertNotRegex(out, rf"sql-coder\.md:\d+.*{provided_by_project}")


