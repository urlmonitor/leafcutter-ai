"""INF-700b-2 -- evidence-gap closers for the CI door and the AC-5 "reached" clause.

Written after the ac-validator's 2026-10-23 question. These tests close evidence gaps on code
that already exists; they were not written to drive new production code, so they are expected
to be GREEN on arrival (TDD-order note: this is deliberate, not an under-specified red).

Decisions taken by the orchestrating session and recorded here:

* Ruleset membership is VERIFIED, but not by a unit test: ``gh api
  repos/urlmonitor/leafcutter-ai/rules/branches/main`` on 2026-10-23 listed the required checks
  ["Lint (ruff)", "Component vocab style (components.json)", "Proof-of-done coverage check
  (BO-2500b)", "Changelog entry present", "AC store valid", "Test suite (pytest)"]. CI has no
  admin token, so no test asserts it; this docstring cites that check.
* "The checking script" of AC-5 is read as the shared verdict (``ability_reference_verdict``
  reached through ``registry_validator``), which both the hook run and the build run reach. The
  standalone ``scripts/check_skill_refs.py`` CLI is a manual diagnostic, consistent with that
  verdict. AC-5 is proven by showing that each gating run's failure DEPENDS on reaching the
  verdict: with the verdict call neutralised in a private copy, the same dangling reference
  passes both runs; unneutralised, both fail.

Doors:

* CI door: ``python <copy>/scripts/build.py --target-dir <empty dir>`` -- the build.py entry and
  flag ci.yml's test-shard step uses (``python scripts/build.py --target-dir .``), but with a
  separate empty target instead of ``.``: the copy's root entries are symlinks into the real
  worktree/shared install, so ``--target-dir <copy>`` would deploy through them (it did once
  and clobbered the shared knowledge_sink.json). Spawned as a real
  subprocess over a private copy of the package (``H.make_build_package``). Exactly THREE
  real build.py runs are made, all in ONE copy, in ``setUpClass``: (1) the unmodified copy,
  (2) the copy with a dangling reference planted in ``templates/skills/signoff/SKILL.md``,
  (3) that same copy with the verdict call stubbed. AC-4 reuses run (1) (it is a genuine build
  of the unmodified private copy, so a fourth identical build would add nothing).
* Hook door: the entry string from the config generated by ``build_precommit_config`` (reused
  from test_inf_700b_2.py) run in a real temporary git repo with the template staged.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import pytest

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
sys.path.insert(0, str(_HERE.parent / "prompt_assembly"))

import _ar_400a_1_support as H  # noqa: E402
import test_inf_700b_2 as base  # noqa: E402

SKILL_TEMPLATE = base.SKILL_TEMPLATE
DANGLING = base.DANGLING
DANGLING_SENTENCE = base.DANGLING_SENTENCE

_VERDICT_CALL = "defs_examined, guides_examined, ref_errors = ability_reference_verdict(package_root, agents)"
_STUBBED_CALL = "defs_examined, guides_examined, ref_errors = (0, 0, [])  # NEUTRALISED by test"

_ENV = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}


def neutralise_verdict(registry_validator: Path) -> None:
    """Replace registry_validator's call to ability_reference_verdict by a stub that finds nothing."""
    text = registry_validator.read_text(encoding="utf-8")
    assert text.count(_VERDICT_CALL) == 1, "registry_validator no longer calls the verdict as expected"
    registry_validator.write_text(text.replace(_VERDICT_CALL, _STUBBED_CALL), encoding="utf-8")


def _build(root: Path, target: Path) -> tuple[int, str]:
    """Run build.py of the private copy into an EMPTY separate target. NOT ``--target-dir <root>``:
    the copy's root entries (``.leafcutter``, ``.claude``, ``tickets`` ...) are symlinks into the
    real worktree and shared install, so building into the copy's own root would deploy through
    them and rewrite the shared install (observed once: it clobbered knowledge_sink.json)."""
    target.mkdir(exist_ok=True)
    cp = subprocess.run([sys.executable, str(root / "scripts" / "build.py"), "--target-dir", str(target)],
                        cwd=str(root), capture_output=True, text=True, timeout=900, check=False, env=_ENV)
    return cp.returncode, cp.stdout + "\n" + cp.stderr


def _names_template_and_skill(out: str) -> list[str]:
    return [ln for ln in out.splitlines() if SKILL_TEMPLATE in ln and DANGLING in ln]


@pytest.mark.shared_layout_mutator
class TestCiDoorThroughBuildPy(unittest.TestCase):
    """Three real build.py runs over ONE private package copy (see module docstring)."""

    @classmethod
    def setUpClass(cls) -> None:
        cls._tmp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls._tmp.cleanup)
        cls.root = H.make_build_package(cls._tmp.name)
        cls.target = Path(cls._tmp.name) / "target"
        cls.clean_rc, cls.clean_out = _build(cls.root, cls.target)
        skill = cls.root / SKILL_TEMPLATE
        skill.write_text(skill.read_text(encoding="utf-8").rstrip("\n") + "\n\n" + DANGLING_SENTENCE + "\n",
                         encoding="utf-8")
        cls.dangling_rc, cls.dangling_out = _build(cls.root, cls.target)
        neutralise_verdict(cls.root / "scripts" / "registry_validator.py")
        cls.neutralised_rc, cls.neutralised_out = _build(cls.root, cls.target)

    def test_ci_door_build_py_refuses_a_dangling_skill_reference(self):
        # covers: INF-700b-2
        # angle: reachability
        """AC-1/AC-2/AC-3 (CI half): build.py --target-dir <copy> (the ci.yml invocation) over a
        copy with a dangling "load the `no-such-skill` skill" in templates/skills/ exits non-zero
        and its output names the template path and the skill. Wrong version caught: a build that
        validates only templates/agents/ (exit 0 here) or fails without naming the file."""
        self.assertNotEqual(self.dangling_rc, 0, self.dangling_out[-2000:])
        self.assertTrue(_names_template_and_skill(self.dangling_out),
                        f"no output line names {SKILL_TEMPLATE} and {DANGLING}: {self.dangling_out[-2000:]}")

    def test_ci_door_build_py_passes_over_the_unmodified_copy_and_reports_no_violation(self):
        # covers: INF-700b-2
        # angle: criterion
        """AC-4 (CI half): the same build over the UNMODIFIED private copy (run 1 of 3, reused as
        the evidence) exits 0 and reports no skill-reference violation. Control row for the
        refusing build: it differs from it by the one planted sentence only."""
        self.assertEqual(self.clean_rc, 0, self.clean_out[-2000:])
        self.assertNotIn(DANGLING, self.clean_out)
        self.assertIsNone(re.search(r"ability does not exist|not granted|names an agent", self.clean_out),
                          self.clean_out[-2000:])

    def test_ac5_build_refusal_depends_on_the_verdict_being_reached(self):
        # covers: INF-700b-2
        # angle: discrimination
        """AC-5 (CI half): with registry_validator's call to ability_reference_verdict stubbed to
        return no findings, the SAME dangling-reference build exits 0 -- so the refusal in the
        unneutralised run is produced by reaching the verdict, not by anything else. Wrong
        version caught: a build that fails on the dangling tree for an unrelated reason (it
        would still fail with the verdict neutralised)."""
        self.assertNotEqual(self.dangling_rc, 0, self.dangling_out[-2000:])
        self.assertEqual(self.neutralised_rc, 0, self.neutralised_out[-2000:])
        self.assertEqual(_names_template_and_skill(self.neutralised_out), [])


@pytest.mark.shared_layout_mutator
class TestAc5HookRefusalDependsOnTheVerdict(base._HookRepoBase):
    """Private hook-repo copy (no build.py spawn); paired unneutralised/neutralised hook runs."""

    def test_ac5_hook_refusal_depends_on_the_verdict_being_reached(self):
        # covers: INF-700b-2
        # angle: discrimination
        """AC-5 (hook half): the generated hook entry over a staged dangling template fails
        (unneutralised), then -- with registry_validator's verdict call stubbed in this private
        copy -- the identical staged change exits 0. Wrong version caught: a hook that refuses
        the tree without ever consulting the verdict."""
        self.stage_append(SKILL_TEMPLATE, DANGLING_SENTENCE)
        before = self.run_hook_entry()
        out_before = before.stdout + "\n" + before.stderr
        self.assertNotEqual(before.returncode, 0, out_before)
        self.assertTrue(_names_template_and_skill(out_before), out_before)
        neutralise_verdict(self.repo / "scripts" / "registry_validator.py")
        after = self.run_hook_entry()
        out_after = after.stdout + "\n" + after.stderr
        self.assertEqual(after.returncode, 0, out_after)
        self.assertEqual(_names_template_and_skill(out_after), [])


if __name__ == "__main__":
    unittest.main()
