from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

_REPO = Path(__file__).resolve().parents[2]
_TEMPLATES = _REPO / "templates" / "scripts" / "commit_guardian"
_SCHEMA = _REPO / "config" / "ac_store_schema.json"
sys.path.insert(0, str(_TEMPLATES))

from _ac_schema_validators import validate_test_contract  # noqa: E402

_PATH = Path("docs/acceptance-criteria/x/ZZE-1a-1.yaml")
_PENDING = "test design pending"
_OLD_TEXT = "approved code AC must declare a test contract"
_INTENT = [{"clause": "it is a valid requirement", "needs_test": True, "reason": "The outcome needs proof."}]
_SPEC = [{"name": "t", "target_dir": "unit_tests/x/", "proves_clause": "it is a valid requirement"}]


def _ac(**overrides) -> dict:
    base = {
        "id": "ZZE-1a-1",
        "readiness": "approved",
        "work_status": "todo",
        "assigned_agent": "python-coder",
        "level": "L2",
    }
    base.update(overrides)
    return base


def test_commit_check_names_test_design_pending_for_intent_without_design():
    # covers: ACD-2500b-2-i
    # angle: criterion
    """validate_test_contract rejects an approved leaf code record with intent only: one error, naming
    the file and "test design pending", and NOT the "must declare a test contract" text (distinct).

    `test_spec: []` and `test_spec: null` read as no design too (exact: one error each).
    """
    for design in ({}, {"test_spec": []}, {"test_spec": None}):
        errors = validate_test_contract(_PATH, _ac(test_intent=_INTENT, **design))
        assert len(errors) == 1, (design, errors)
        assert str(_PATH) in errors[0] and _PENDING in errors[0], errors
        assert _OLD_TEXT not in errors[0], errors


def test_commit_check_boundaries_keep_the_old_text_and_the_old_grandfathering():
    # covers: ACD-2500b-2-i
    # angle: boundary
    """The new message fires only for intent-without-design; every neighbour keeps today's verdict.

    Control rows: no intent and no design keeps the old text and does NOT say "test design pending";
    an EMPTY test_intent list is no intent (old text); intent plus any test_spec passes (the commit
    check tests only the absence of a design, partial coverage is judged at approval, note item 9);
    a record at readiness "reviewed", one already "done", and a non-code leaf with intent are exempt,
    exactly as before (forward ratchet).
    """
    no_intent = validate_test_contract(_PATH, _ac())
    assert len(no_intent) == 1 and _OLD_TEXT in no_intent[0] and _PENDING not in no_intent[0]
    empty_intent = validate_test_contract(_PATH, _ac(test_intent=[]))
    assert len(empty_intent) == 1 and _OLD_TEXT in empty_intent[0] and _PENDING not in empty_intent[0]

    assert validate_test_contract(_PATH, _ac(test_intent=_INTENT, test_spec=_SPEC)) == []
    assert validate_test_contract(_PATH, _ac(test_intent=_INTENT, readiness="reviewed")) == []
    assert validate_test_contract(_PATH, _ac(test_intent=_INTENT, work_status="done")) == []
    non_code = _ac(test_intent=_INTENT, assigned_agent="documentation-expert", change_target="docs")
    assert validate_test_contract(_PATH, non_code) == []
    positive = validate_test_contract(_PATH, _ac(test_intent=_INTENT))
    assert len(positive) == 1 and _PENDING in positive[0], "the intent row (positive control) must fire"


def test_missing_contract_message_chooses_the_text_from_the_intent():
    # covers: ACD-2500b-2-i
    # angle: seam
    """missing_contract_message(path, data) is the one place the two texts live.

    With a non-empty test_intent it names the file and "test design pending"; without one it returns
    the existing text moved verbatim (it still names the file, carries the closing "ACs are the source
    of truth for tests." sentence, and has no "test design pending"). validate_test_contract's error
    for each case equals that message, so the two never drift.
    """
    from _test_design_pending import missing_contract_message  # noqa: PLC0415

    pending = missing_contract_message(_PATH, _ac(test_intent=_INTENT))
    assert str(_PATH) in pending and _PENDING in pending and _OLD_TEXT not in pending

    old = missing_contract_message(_PATH, _ac())
    assert str(_PATH) in old and _OLD_TEXT in old and "ACs are the source of truth for tests." in old
    assert _PENDING not in old

    assert validate_test_contract(_PATH, _ac(test_intent=_INTENT)) == [pending]
    assert validate_test_contract(_PATH, _ac()) == [old]


def _hook_run(tmp_path: Path, record: dict):
    root = tmp_path / "hook_repo"
    (root / "config").mkdir(parents=True)
    shutil.copy2(_SCHEMA, root / "config" / "ac_store_schema.json")
    store = root / "docs" / "acceptance-criteria"
    store.mkdir(parents=True)
    target = store / f"{record['id']}.yaml"
    target.write_text(yaml.safe_dump(record, sort_keys=False, allow_unicode=True), encoding="utf-8")
    env = {
        **os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8",
        "HOOK_ROOT": str(root), "HOOK_TEST_STAGED_FILES": str(target), "HOOK_NO_GIT": "1",
    }
    return subprocess.run(
        [sys.executable, str(_TEMPLATES / "check_ac_schema.py")],
        capture_output=True, text=True, encoding="utf-8", cwd=str(_REPO), timeout=60, env=env,
    )


def _store_record(**overrides) -> dict:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "ac_store"))
    from _acd_2500_schema_probe import base_record  # noqa: PLC0415

    fields = {"readiness": "approved", "work_status": "todo", "assigned_agent": "python-coder", "level": "L2"}
    fields.update(overrides)
    return base_record("ZZE-2a-1", **fields)


def test_commit_check_rejects_approved_intent_without_design(tmp_path):
    # covers: ACD-2500b-2-i
    # angle: failure
    """The real commit hook (subprocess) rejects the staged record, naming the file and the reason.

    Entry point: `python templates/scripts/commit_guardian/check_ac_schema.py` (the hook's own runner)
    over a tmp repo holding one staged record serialised with yaml.safe_dump. Non-zero exit, the file
    name and "test design pending" in the output. Controls through the same runner: the same record
    with a design is accepted (exit 0), and one with no intent and no design is rejected with the old
    text and WITHOUT "test design pending".
    """
    rejected = _hook_run(tmp_path / "pending", _store_record(test_intent=_INTENT))
    out = rejected.stdout + rejected.stderr
    assert rejected.returncode != 0, out
    assert "ZZE-2a-1.yaml" in out and _PENDING in out, out

    accepted = _hook_run(tmp_path / "designed", _store_record(test_intent=_INTENT, test_spec=_SPEC))
    assert accepted.returncode == 0, accepted.stdout + accepted.stderr

    old = _hook_run(tmp_path / "old", _store_record())
    old_out = old.stdout + old.stderr
    assert old.returncode != 0 and _OLD_TEXT in old_out and _PENDING not in old_out, old_out
