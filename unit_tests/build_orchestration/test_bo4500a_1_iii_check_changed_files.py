"""
MODULE: unit_tests/build_orchestration/test_bo4500a_1_iii_check_changed_files.py
GOAL: RED tests for BO-4500a-1-iii -- a file a check changes OUTSIDE the caller's
      list is left out of the commit and named in the answer's unlisted_changes;
      a check's rewrite of a NAMED file is committed and reported in paths.

Production target: templates/scripts/commit_changes.py (does not exist yet).
The "check" is a real git pre-commit hook installed in the scratch repo that
rewrites files and runs `git add` mid-commit -- KI-BO-029's mechanism 2.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _commit_step_support import StepScenario  # noqa: E402

NAMED = ["docs/known-issues/a.md", "docs/known-issues/b.md", "docs/known-issues/c.md"]
INDEX = "docs/INDEX.md"
REGENERATED = "# index regenerated by the check\n"

# Transform-tier fixture check: regenerates docs/INDEX.md and stages it.
REGEN_HOOK = f"printf '%s\\n' '# index regenerated by the check' > {INDEX}\ngit add {INDEX}\n"
# Fixing check: appends a fix to a.md once (idempotent) and stages it.
FIX_A_HOOK = (
    "grep -q 'fixed by check' docs/known-issues/a.md || "
    "printf '%s\\n' 'fixed by check' >> docs/known-issues/a.md\n"
    "git add docs/known-issues/a.md\n"
)


def _scenario(case: unittest.TestCase, hook: str) -> StepScenario:
    sc = StepScenario(case)
    baseline = {rel: f"# {rel}\n" for rel in NAMED}
    baseline[INDEX] = "# index\n"
    sc.seed_and_commit(baseline)
    for rel in NAMED:
        sc.write(rel, f"# {rel} edited\n")
    sc.install_hook(hook)
    return sc


class TestCheckChangedFilesOutsideTheList(unittest.TestCase):
    def test_check_regenerated_index_is_left_out_of_the_commit(self):
        # covers: BO-4500a-1-iii
        # angle: criterion
        """AC BO-4500a-1-iii: the commit holds the three named files and not docs/INDEX.md."""
        sc = _scenario(self, REGEN_HOOK)
        answer = sc.run_step(NAMED)
        self.assertEqual(answer.get("status"), "committed", answer)
        self.assertEqual(sc.head_files(), sorted(NAMED))
        self.assertNotIn(INDEX, sc.head_files())

    def test_left_out_file_keeps_the_checks_content_unstaged(self):
        # covers: BO-4500a-1-iii
        # angle: criterion
        """AC BO-4500a-1-iii: docs/INDEX.md keeps the check's content in the working tree, unstaged."""
        sc = _scenario(self, REGEN_HOOK)
        answer = sc.run_step(NAMED)
        self.assertEqual(answer.get("status"), "committed", answer)
        self.assertEqual(sc.read(INDEX).decode(), REGENERATED)
        self.assertEqual(sc.porcelain().get(INDEX), " M", "INDEX must be modified, not staged")
        self.assertEqual(sc.staged_names(), [])

    def test_answer_reports_left_out_file_in_unlisted_changes(self):
        # covers: BO-4500a-1-iii
        # angle: discrimination
        """AC BO-4500a-1-iii: unlisted_changes names docs/INDEX.md; paths does not.

        Wrong versions this must catch: including the check-staged file silently
        (it would be in the commit and in paths); dropping it without reporting
        it (unlisted_changes empty).
        """
        sc = _scenario(self, REGEN_HOOK)
        answer = sc.run_step(NAMED)
        self.assertEqual(answer.get("status"), "committed", answer)
        self.assertEqual(answer.get("unlisted_changes"), [INDEX])
        self.assertEqual(sorted(answer.get("paths") or []), sorted(NAMED))
        self.assertNotIn(INDEX, answer["paths"])
        self.assertNotIn(INDEX, sc.head_files())

    def test_check_rewrite_of_a_named_file_is_committed_and_reported_in_paths(self):
        # covers: BO-4500a-1-iii
        # angle: boundary
        """AC BO-4500a-1-iii: a check's rewrite of a.md lands in the commit; a.md is in paths."""
        sc = _scenario(self, FIX_A_HOOK)
        answer = sc.run_step(NAMED)
        self.assertEqual(answer.get("status"), "committed", answer)
        self.assertIn("fixed by check", sc.committed_text("docs/known-issues/a.md"))
        self.assertIn("docs/known-issues/a.md", answer.get("paths") or [])
        self.assertEqual(answer.get("unlisted_changes"), [])
        self.assertEqual(sc.head_files(), sorted(NAMED))


if __name__ == "__main__":
    unittest.main()
